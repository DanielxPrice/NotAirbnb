const { test, expect } = require('@playwright/test');
const sharp = require('sharp');
test.afterAll(async ({ request }) => { await request.post('/__shutdown'); });
test('host publishes a property; traveler books; host accepts; both exchange persistent messages', async ({ browser }) => {
  const hostContext = await browser.newContext();
  const guestContext = await browser.newContext();
  const host = await hostContext.newPage();
  const guest = await guestContext.newPage();
  const errors = [];
  host.on('pageerror', error => errors.push(error.message));
  guest.on('pageerror', error => errors.push(error.message));
  async function register(page, email, role) {
    await page.goto('/register');
    await page.getByLabel('Email address').fill(email);
    await page.getByLabel('Password', { exact: true }).fill('Password123!');
    await page.getByLabel('Role').selectOption(role);
    await page.getByRole('button', { name: 'Register', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Logout' })).toBeVisible();
  }
  await register(host, 'browser-host@example.com', 'host');
  await host.getByRole('link', { name: 'My Listings' }).click();
  await host.getByRole('button', { name: 'Add New Listing' }).click();
  for (const [label, value] of [['Title', 'Browser Beach House'], ['Location', 'Miami'], ['Price per night', '125.25'], ['Description', 'A beachfront home for the integration test'], ['Bedrooms', '2'], ['Bathrooms', '1'], ['Max Guests', '4']]) await host.getByLabel(label, { exact: true }).fill(value);
  const image = await sharp({ create: { width: 100, height: 100, channels: 3, background: '#fb7185' } }).png().toBuffer();
  await host.locator('input[type=file]').setInputFiles({ name: 'house.png', mimeType: 'image/png', buffer: image });
  await expect(host.getByRole('button', { name: 'Add Listing', exact: true })).toBeEnabled();
  await host.getByRole('button', { name: 'Add Listing', exact: true }).click();
  await expect(host.getByRole('heading', { name: 'Browser Beach House' })).toBeVisible();
  await register(guest, 'browser-guest@example.com', 'traveler');
  await guest.getByRole('link', { name: 'Find a Place' }).click();
  await guest.getByRole('heading', { name: 'Browser Beach House' }).click();
  await guest.reload();
  await expect(guest.getByRole('heading', { name: 'Browser Beach House' })).toBeVisible();
  const date = n => new Date(Date.now() + n * 86400000).toISOString().slice(0, 10);
  await guest.getByLabel('Check-in', { exact: true }).fill(date(10));
  await guest.getByLabel('Check-out', { exact: true }).fill(date(12));
  await guest.getByLabel('Guests', { exact: true }).fill('2');
  await guest.getByRole('button', { name: 'Add to Cart' }).click();
  await expect(guest.getByRole('heading', { name: 'Your Cart' })).toBeVisible();
  await guest.reload();
  await expect(guest.getByText('$250.50', { exact: true })).toBeVisible();
  await guest.getByRole('button', { name: 'Submit Booking Requests' }).click();
  await expect(guest.getByRole('status')).toContainText('1 booking request(s) submitted');
  await host.getByRole('link', { name: 'Bookings', exact: true }).click();
  await host.getByRole('button', { name: 'Accept', exact: true }).click();
  await expect(host.getByText('accepted ? Hosting', { exact: true })).toBeVisible();
  await guest.getByRole('link', { name: 'My Bookings', exact: true }).click();
  await guest.getByRole('button', { name: 'Simulate Payment' }).click();
  await expect(guest.getByRole('status')).toContainText('No money was charged');
  await expect(guest.getByText('Paid (simulated)', { exact: true })).toBeVisible();
  await guest.reload();
  await expect(guest.getByText('Paid (simulated)', { exact: true })).toBeVisible();
  await expect(guest.getByRole('button', { name: 'Simulate Payment' })).toHaveCount(0);
  await guest.getByRole('button', { name: 'Message Host' }).click();
  await guest.getByRole('textbox', { name: 'Message', exact: true }).fill('When can we check in?');
  await guest.getByRole('button', { name: 'Send message' }).click();
  await expect(guest.getByText('When can we check in?', { exact: true })).toBeVisible();
  await host.getByRole('link', { name: 'Messages', exact: true }).click();
  await host.getByRole('button', { name: /Browser Beach House/ }).click();
  await expect(host.getByText('When can we check in?', { exact: true })).toBeVisible();
  await host.getByRole('textbox', { name: 'Message', exact: true }).fill('After 3 PM.');
  await host.getByRole('button', { name: 'Send message' }).click();
  await guest.reload();
  await expect(guest.getByText('After 3 PM.', { exact: true })).toBeVisible();
  await guest.getByRole('link', { name: 'Account', exact: true }).click();
  await guest.getByLabel('Display name').fill('Traveler Updated');
  await guest.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(guest.getByRole('status')).toContainText('Account updated');
  await guest.reload();
  await expect(guest.getByLabel('Display name')).toHaveValue('Traveler Updated');
  await guest.setViewportSize({ width: 390, height: 844 });
  expect(await guest.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await guest.getByRole('button', { name: 'Logout' }).click();
  await guest.goto('/account');
  await expect(guest.getByRole('heading', { name: 'Sign in to your account' })).toBeVisible();
  expect(errors).toEqual([]);
  await hostContext.close();
  await guestContext.close();
});
